#!/usr/bin/env python3
"""Generate WebGLStubs.gen.inc from glad.h.

WebGL2 (GLES 3.0) implements only a subset of the desktop GL entry points glad knows.
Emscripten's GetProcAddress returns null for the rest, and calling a null wasm function
pointer traps. This emits one correctly-typed no-op stub per glad entry point plus a
table, so WebGLCompat can fill every null pointer and count what the engine calls.

usage: gen_stubs.py <glad.h> <out.inc>
"""
import re
import sys

src = open(sys.argv[1]).read()
pat = re.compile(
    r"typedef\s+(?P<ret>[^()]+?)\s*\(APIENTRYP\s+(?P<td>PFNGL\w+)\)\((?P<args>[^;]*)\);\s*"
    r"GLAPI\s+(?P=td)\s+glad_(?P<name>gl\w+);")
out = ["// generated by gen_stubs.py from glad.h; do not edit\n"]
names = []
for m in pat.finditer(src):
    ret, args, name, td = m.group("ret").strip(), m.group("args").strip(), m.group("name"), m.group("td")
    idx = len(names)
    names.append((name, td))
    body = f"Hit({idx});"
    if ret != "void":
        body += f" return ({ret})0;"
    out.append(f"static {ret} APIENTRY stub_{name}({args}) {{ {body} }}\n")
out.append(f"\nstatic constexpr int NUM_GL_FUNCS = {len(names)};\n")
out.append("static const char* const glFuncNames[NUM_GL_FUNCS] = {\n")
out += [f'\t"{n}",\n' for n, _ in names]
out.append("};\n\nstatic void FillNullEntryPoints() {\n")
out += [f"\tif (glad_{n} == nullptr) {{ glad_{n} = stub_{n}; stubbed[{i}] = true; }}\n" for i, (n, _) in enumerate(names)]
out.append("}\n")
open(sys.argv[2], "w").write("".join(out))
print(f"gen_stubs: {len(names)} GL entry points")
